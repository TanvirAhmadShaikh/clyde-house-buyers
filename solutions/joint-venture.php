    <h2>How a JV differs from an assisted sale.</h2>
    <p>An <a href="/solutions/assisted-sale.php">assisted sale</a> is structured for someone who definitely wants to sell — we refurb, sell at market, and the property changes hands at the end. A JV is for someone who'd <em>prefer not to sell</em> but wants to add value: maybe refinance instead, retain as a rental, or sell at a much higher figure than the as-is value would have allowed.</p>
    <p>Practically, the differences:</p>
    <ul>
      <li><strong>Ownership</strong> — in a JV, you retain ownership throughout (or share it via a partnership/SPV). In an assisted sale, ownership transfers at the end.</li>
      <li><strong>Exit</strong> — JV exits can be refinance, retain, or sale. Assisted sale always ends in a sale.</li>
      <li><strong>Risk profile</strong> — JV partners share more risk and reward. Assisted sale puts most risk on us.</li>
      <li><strong>Complexity</strong> — JV requires more legal structuring (partnership agreement, SPV, or contractual JV). Assisted sale is contractually simpler.</li>
    </ul>
