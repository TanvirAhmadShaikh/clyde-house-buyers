    <div class="text-center mb-4">
      <span class="eyebrow">Common questions</span>
      <h2>Questions sellers ask us about assisted sale.</h2>
    </div>
    <div class="faq" data-schema="true">
      <details><summary>Who actually owns the property during the refurb?</summary><p>You do. The title doesn't transfer to us until the final sale completes. We work on the property under a formal written agreement drafted by Scottish solicitors — secured by a standard security registered against the property — that gives us the right to manage the refurb and sell on your behalf, and to recover our refurb costs from the sale proceeds. But you remain the legal owner throughout.</p></details>
      <details><summary>What's the typical split between you and the seller?</summary><p>It depends on the project's risk and scale. For straightforward cosmetic refurbs, splits are often 60/40 or 50/50 in the seller's favour. For heavy structural work where we carry more risk, splits move closer to 50/50 or 40/60. We model the numbers transparently before you commit — and you can walk away if the split doesn't suit you.</p></details>
      <details><summary>What happens if the refurb costs more than expected?</summary><p>We absorb it. The refurb budget is capped at the figure we agree before work starts. Unexpected issues — dry rot, structural problems, failed inspections — are our risk to manage, not yours. Your minimum payout is unchanged.</p></details>
      <details><summary>What if the refurbished property sells for less than expected?</summary><p>You still receive your full agreed "as-is" price. The uplift just ends up smaller — and your share of a smaller uplift is smaller too. But you can never receive less than your guaranteed minimum, regardless of the final sale price.</p></details>
      <details><summary>Can I still live in the property during the refurb?</summary><p>Usually not — most assisted-sale properties are empty or being inherited. If you're still living there, we'd typically suggest a cash purchase instead, since refurbing around an occupied home rarely works well.</p></details>
      <details><summary>How long does the whole process take?</summary><p>From signing to money in your account, typically 8–16 weeks. Roughly: 2 weeks for legals and planning, 4–10 weeks for refurb depending on scope, then 2–4 weeks to sell and complete.</p></details>
      <details><summary>Do I need a Home Report?</summary><p>Yes — every Scottish property sale needs one. We pay for and arrange the Home Report for the post-refurb sale. You don't need to organise or pay for it.</p></details>
      <details><summary>What happens if I change my mind partway through?</summary><p>You can walk away before work starts at no cost. Once the refurb is underway, we'd need to recover our costs from you if you want to keep the property — that's standard. We don't lock people in, but we do need to protect ourselves once we've spent money on your property.</p></details>
      <details><summary>How is this different from a property developer just buying my house?</summary><p>A developer pays you the "as-is" price and keeps 100% of the uplift. With an assisted sale, you keep a share — typically tens of thousands more than a developer would pay. You're effectively partnering with us on the project rather than selling to us cheap.</p></details>
      <details><summary>Is an assisted sale taxed differently?</summary><p>Your share is treated the same as any property sale. If it's not your main residence, Capital Gains Tax may apply. We're not tax advisors — a quick conversation with an accountant is worth having. For most inherited properties sold within a reasonable timeframe, the tax treatment is straightforward.</p></details>
