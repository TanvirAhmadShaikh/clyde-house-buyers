    <h2>Stage 1 — First contact (Day 0–1)</h2>
    <p>The first conversation is usually 10–15 minutes. We ask three things: <strong>where the property is, what condition it's in, what's going on for you</strong>. That last part matters because the right route depends on it — someone facing repossession in three weeks needs a different solution to someone exploring a landlord exit over the next six months.</p>
    <p>You don't need to have everything figured out. You don't need photos or documents. You just need to be willing to talk for ten minutes.</p>

    <h2>Stage 2 — Valuation &amp; route proposal (Day 1–3)</h2>
    <p>We do a desktop valuation using local comparables, recent sold-prices, and our own area knowledge. For tenanted property we also model yield. For properties needing work we model both the cash sale and the assisted sale routes.</p>
    <p>Within 48 hours of the first call, we send (by email or phone, your preference): a clear valuation, the route we'd recommend, and a comparison of the alternatives. <strong>You're under no obligation at this stage</strong> — many sellers take a week or two to think it through.</p>

    <h2>Stage 3 — Viewing &amp; firm offer (Day 3–7)</h2>
    <p>If our valuation looks right to you and you'd like to proceed, we'll arrange one viewing. Usually 30–45 minutes. We look at condition, take notes, photograph anything that affects pricing, then come back with a firm written offer.</p>
    <p>The written offer covers: the price, the route, who pays which costs, the proposed timeline, and anything specific to your situation. Your solicitor reviews it and advises you.</p>

    <h2>Stage 4 — Solicitors &amp; missives (Day 7–21)</h2>
    <p>Once you accept the offer, both sides instruct solicitors. Missives — formal letters between solicitors — are exchanged until terms are fully agreed. Once missives "conclude," the sale is legally binding on both sides. No gazumping, no last-minute withdrawals.</p>
    <p>During this period, your solicitor will: confirm the title is clean, settle any outstanding charges or notices, agree the settlement date, and arrange the transfer of any keys.</p>

    <h2>Stage 5 — Settlement (Day 14–28)</h2>
    <p>Settlement day — the day completion happens. Your solicitor releases the title; ours releases the funds. The mortgage (if any) is paid off directly. Net proceeds land in the account you nominate, usually the same day.</p>
    <p>If you're still in the property, you hand over keys on settlement day. If it's empty, we arrange access. Done.</p>

    <h2>What you don't have to do</h2>
    <ul>
      <li>You don't pay for a Home Report (not needed for our cash purchase)</li>
      <li>You don't pay legal fees (we cover them on a cash purchase)</li>
      <li>You don't pay an estate-agent commission</li>
      <li>You don't clear the property (we handle that after completion)</li>
      <li>You don't fix anything before sale</li>
      <li>You don't deal with chains, viewings, or buyer drop-outs</li>
    </ul>

    <h2>What you do need to do</h2>
    <ul>
      <li>Engage a Scottish solicitor (we can recommend firms we work with)</li>
      <li>Provide standard ID and AML documentation</li>
      <li>Be available for one viewing (typically)</li>
      <li>Sign the missives documents your solicitor sends</li>
      <li>Hand over keys on settlement day</li>
    </ul>
