    <h2>What an estate agent actually costs you.</h2>
    <p>A traditional sale in Scotland isn't just the agent's commission — typically 1–1.5% plus VAT. It's also:</p>
    <ul>
      <li><strong>The Home Report</strong> — £300–£600, paid upfront before you can market the property, whether or not it sells.</li>
      <li><strong>Time on the market</strong> — weeks or months of viewings, open days, and keeping the house presentable.</li>
      <li><strong>Chain risk</strong> — a buyer whose own sale collapses, a survey that comes in low, an offer withdrawn after weeks of waiting.</li>
      <li><strong>No certainty</strong> — the agent is paid to find a buyer, not to guarantee one.</li>
    </ul>
    <p>For plenty of properties an agent is still the right call — a well-presented home in a fast-moving area will usually get the best price on the open market. But if the property needs work, the timing is tight, or you simply want the process over with, the agent route can cost more than it returns.</p>
