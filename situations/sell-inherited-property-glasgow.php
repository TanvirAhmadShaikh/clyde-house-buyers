    <span class="eyebrow">The Scottish process</span>
    <h2>Selling an inherited property in Scotland — the practical steps.</h2>
    <p>Selling an inherited property in Scotland is slightly different from England, and a lot of online advice misses the Scottish specifics. Here's the basic sequence.</p>

    <h3>Step 1 — Confirmation</h3>
    <p>The Scottish equivalent of probate. The executor applies to the Sheriff Court for a "grant of confirmation" — the legal authority to deal with the deceased's assets. Until confirmation is granted, you can't legally complete a property sale, though you can start the conversation and agree a route. Typical timeline: 4–12 weeks.</p>

    <h3>Step 2 — Property valuation and route decision</h3>
    <p>While confirmation is processing, this is the right time to think about <em>how</em> to sell. Three routes typically apply:</p>
    <ul>
      <li><strong>Cash sale</strong> — fastest, cleanest, typically 75–85% of market value.</li>
      <li><strong>Assisted sale</strong> — we refurbish at our cost, sell at market value, split the uplift. Usually nets significantly more than a cash sale if the property needs work.</li>
      <li><strong>Open market</strong> — full market value if it sells, but 3–9 months of viewings, agent fees, and uncertainty.</li>
    </ul>
    <p>We'll model all three for your specific property — no pressure to pick ours.</p>

    <h3>Step 3 — Home Report (or not)</h3>
    <p>Open-market sales in Scotland require a Home Report. For a cash sale to us, it's not needed. For an assisted sale, we organise and pay for it.</p>

    <h3>Step 4 — Missives</h3>
    <p>Once confirmation is granted and you've agreed a price and route, your solicitor and ours exchange formal letters. Once concluded, the sale is legally binding — no gazumping, no last-minute pull-outs.</p>

    <h3>Step 5 — Settlement and funds</h3>
    <p>Settlement date is whatever you choose. We can complete in 14 days from confirmation, or wait months. On settlement day, your solicitor releases the title, ours releases the funds, and the money lands in the estate's bank account.</p>

    <h3>Tax — a brief note</h3>
    <p>We're not tax advisors, but the basics: Inheritance Tax is handled at the estate level. Capital Gains Tax may apply if the value rises between the date of death and the date of sale. For most inherited properties sold within a reasonable timeframe, CGT is straightforward or nil. A short conversation with the estate solicitor or an accountant is worth having.</p>
