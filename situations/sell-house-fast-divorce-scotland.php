    <h3>1. Initial conversation — usually with one party</h3>
    <p>Often one spouse contacts us first. We can talk to either party initially, but we won't proceed without both being on the same page. If only one party wants to sell, this isn't the route — that's family-law territory, not ours.</p>

    <h3>2. Joint valuation</h3>
    <p>We value the property once and share the figure with both sides. No "your figure versus my figure" — one number, transparent methodology.</p>

    <h3>3. Both parties' solicitors involved from day one</h3>
    <p>You each use your own family-law or conveyancing solicitor. We deal through them. They review our offer, advise their client, negotiate if needed. We don't put pressure on either party to sign quickly.</p>

    <h3>4. Missives concluded with both signatures</h3>
    <p>Once you've both agreed terms, missives are concluded by both solicitors. From this point the sale is legally binding on both sides.</p>

    <h3>5. Settlement and proceeds split</h3>
    <p>On completion, the sale proceeds are paid to the solicitors holding the title, who then distribute according to the financial settlement you've agreed (or, if mid-settlement, hold in escrow pending the order). The lender is paid off, costs are deducted, and the net is split per your agreement.</p>
