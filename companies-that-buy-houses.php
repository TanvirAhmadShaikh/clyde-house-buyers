        <p>These don't buy anything. They collect your enquiry and sell it on — sometimes to several buyers at once. You may get multiple calls and offers that then change once someone views. Not inherently bad, but you should know if that's what you've contacted.</p>
      </div>
      <div class="pro-card">
        <h3>Auction and "modern method of auction" firms</h3>
        <p>Not a direct sale — your property is listed and sold to the highest bidder, usually with a reservation fee paid by the buyer and a fixed timescale. Faster than the open market, but not guaranteed and not fee-free in every case.</p>
