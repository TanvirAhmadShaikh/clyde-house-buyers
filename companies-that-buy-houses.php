<section class="section section-alt">
  <div class="container-narrow prose">
    <h2>What to watch for.</h2>
    <ul>
      <li><strong>A price cut near completion.</strong> The most common complaint. A strong opening offer, then a "survey issue" or "market change" knocks tens of thousands off once you're committed and short of time.</li>
      <li><strong>"Cash" that isn't cash.</strong> Ask for proof of funds. Some buyers use bridging finance or need to line up an end buyer first, which reintroduces the delay and fall-through risk you were trying to avoid.</li>
      <li><strong>Tie-in agreements.</strong> A contract that locks you in for a period, blocks you from selling to anyone else, or charges a fee if you walk away.</li>
      <li><strong>Upfront or "admin" fees.</strong> A genuine buyer doesn't charge you to buy your house.</li>
      <li><strong>Lead sites posing as buyers.</strong> If you're getting calls from several companies, your enquiry was sold on.</li>
      <li><strong>Pressure.</strong> "This offer is only valid today" is a sales tactic, not a market reality.</li>
    </ul>
  </div>
</section>

