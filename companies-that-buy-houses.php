    <h2>How regulated is this?</h2>
    <p>Buying property from a homeowner isn't regulated by the FCA the way a mortgage or investment would be. The protections that do apply:</p>
    <ul>
      <li><strong>Redress schemes</strong> — property buyers should be members of the Property Redress Scheme or The Property Ombudsman, which gives you somewhere to escalate a complaint.</li>
      <li><strong>Anti-money-laundering supervision</strong> — high-value dealers and estate agency businesses must register with HMRC and carry out ID checks.</li>
      <li><strong>Consumer protection law</strong> — misleading pricing and high-pressure selling are covered by the Consumer Protection from Unfair Trading Regulations, enforced by National Trading Standards. In 2021 several "sell house fast" firms were subject to enforcement action over undisclosed referral fees and misleading claims.</li>
      <li><strong>The National Association of Property Buyers (NAPB)</strong> — a voluntary trade body whose members sign up to a code of practice.</li>
    </ul>
