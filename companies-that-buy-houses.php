    <h2>Why the offer is below market value.</h2>
    <p>A genuine buyer is taking on risk and cost that a mortgage buyer on the open market doesn't:</p>
    <ul>
      <li><strong>Their own money is tied up</strong> from the day they buy until the day they sell or let — that carries a cost.</li>
      <li><strong>They carry the risk</strong> of the market moving, the refurb costing more than expected, or the property being harder to sell on than it looked.</li>
      <li><strong>They're paying for speed and certainty</strong> — no marketing period, no chain, a guaranteed completion date. That's the value you're buying from them, and it has a price.</li>
      <li><strong>They cover costs you'd normally pay</strong> — a genuine buyer pays your legal fees and doesn't need a Home Report.</li>
    </ul>
    <p>The discount is the deal. What matters is that the number you're quoted at the start is the number you get at completion.</p>
