    <h2>What "companies that buy houses" means.</h2>
    <p>The phrase covers any business that buys residential property directly from the owner, rather than acting as an agent to find a buyer. You sell to the company; the company either keeps the property to rent out, refurbishes and resells it, or sells it on to another investor.</p>
    <p>The appeal is simple: no viewings, no open market, no chain, a fixed completion date, and — with a genuine buyer — no fees. The cost is that you sell below full market value. A direct sale to a property company is typically <strong>75–85% of what the property would fetch on the open market</strong>, sometimes less for properties needing significant work.</p>
