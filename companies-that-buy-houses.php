    <ul>
      <li>Are you the company that will actually buy the property, or will you pass my details on?</li>
      <li>Can you show proof of funds before missives?</li>
      <li>Is the offer fixed, and under what circumstances would it change?</li>
      <li>Am I tied into anything by talking to you or accepting a valuation?</li>
      <li>Who pays the legal fees, and is a Home Report needed?</li>
      <li>What's a realistic completion date, and what could delay it?</li>
      <li>Are you a member of a redress scheme (Property Redress Scheme or The Property Ombudsman), and are you registered for anti-money-laundering supervision?</li>
    </ul>
